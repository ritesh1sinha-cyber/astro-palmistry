async def _run_review(
    session: Session,
    upload_path: Path,
    stem: str,
    file_index: int,
    total_files: int,
    alm_id: str,
):
    workspace = session.dir / f"{file_index:02d}_{stem}"
    workspace.mkdir(parents=True, exist_ok=True)

    async def log(msg: str, kind: str = "info"):
        await session.emit(msg, kind)

    try:
        # 1. Extract PPTX text
        await log(f"🔍 [{file_index}/{total_files}] Extracting text from {upload_path.name}…")
        loop = asyncio.get_running_loop()
        pptx_text = await loop.run_in_executor(None, _extract_pptx_text, str(upload_path))
        await log(f"   ✓ Extracted {len(pptx_text):,} characters.", "info")

        # 2. Write context file for Cursor to read
        (workspace / "backtrack_report_content.txt").write_text(pptx_text, encoding="utf-8", errors="replace")

        # 3. Optional ALM cross-reference
        alm_section = ""
        if alm_id:
            await log(f"🔗 Fetching ALM details for {alm_id}…")
            alm_data = await loop.run_in_executor(None, _fetch_alm_details, alm_id)
            if alm_data:
                alm_section = (
                    f"\n\n=== ALM / BUG DETAILS (ID: {alm_id}) ===\n"
                    + alm_data
                    + "\n=== END ALM DETAILS ===\n"
                )
                await log(f"   ✓ ALM details fetched ({len(alm_data):,} chars).", "info")
            else:
                await log("   ⚠ Could not fetch ALM details — proceeding without cross-reference.", "warn")

        # 4. Build Cursor prompt
        prompt = (
            BACKTRACK_REVIEW_PROMPT
            + f"\n\n=== BACKTRACK REPORT CONTENT (File: {upload_path.name}) ===\n"
            + pptx_text
            + "\n=== END OF REPORT CONTENT ===\n"
            + alm_section
            + "\n\nCreate the file: backtrack_review.html  (in the current workspace directory)\n"
        )

        # 5. Delete stale report
        stale = workspace / "backtrack_review.html"
        if stale.exists():
            stale.unlink()

        # 6. Run Cursor AI
        await log(f"🤖 [{file_index}/{total_files}] Sending to Cursor AI (this may take a few minutes)…")
        await session.emit_raw({"kind": "progress", "value": 30 + file_index * 10, "msg": ""})

        if not _cursor_automation:
            await log("❌ cursor-agent not found. Install Cursor CLI and add to PATH.", "error")
            await session.emit_raw({"kind": "report_error", "name": upload_path.name, "msg": ""})
            return

        ok, out_file = await loop.run_in_executor(
            None,
            _cursor_automation.run,
            str(workspace),
            prompt,
            ["backtrack_review.html"],
            12,
        )

        # 7. Result
        report_path = workspace / "backtrack_review.html"
        if ok and report_path.exists():
            rel = report_path.relative_to(SESSIONS_DIR)
            url = f"/files/{rel.as_posix()}"
            await log(f"✅ [{file_index}/{total_files}] Review complete: {upload_path.name}", "success")
            await session.emit_raw({"kind": "report", "name": upload_path.stem, "url": url, "msg": ""})
        else:
            await log(f"❌ [{file_index}/{total_files}] backtrack_review.html was not generated for {upload_path.name}.", "error")
            await session.emit_raw({"kind": "report_error", "name": upload_path.name, "msg": ""})

    except Exception as e:
        await log(f"❌ Unexpected error for {upload_path.name}: {e}", "error")
        await session.emit_raw({"kind": "report_error", "name": upload_path.name, "msg": ""})
    finally:
        if file_index == total_files:
            await session.emit_raw({"kind": "done", "success": True, "msg": "All files processed."})


