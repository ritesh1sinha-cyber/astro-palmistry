# ─────────────────────────── session store ────────────────────────────
class Session:
    def __init__(self, session_id: str):
        self.id = session_id
        self.dir = SESSIONS_DIR / session_id
        self.dir.mkdir(parents=True, exist_ok=True)
        self.events: List[str] = []
        self.status: str = "idle"         # idle | running | done | error
        self.reports: Dict[str, str] = {}  # filename → absolute path
        self.ws_connections: List[WebSocket] = []
        self._lock = asyncio.Lock()

    async def emit(self, msg: str, kind: str = "info"):
        ts = datetime.now().strftime("%H:%M:%S")
        entry = json.dumps({"ts": ts, "msg": msg, "kind": kind})
        self.events.append(entry)
        await self._broadcast(entry)

    async def emit_raw(self, payload: dict):
        """Emit a custom payload dict (for report/done/progress signals)."""
        if "ts" not in payload:
            payload["ts"] = datetime.now().strftime("%H:%M:%S")
        entry = json.dumps(payload)
        self.events.append(entry)
        await self._broadcast(entry)

    async def _broadcast(self, entry: str):
        dead = []
        for ws in list(self.ws_connections):
            try:
                await ws.send_text(entry)
            except Exception:
                dead.append(ws)
        for ws in dead:
            try:
                self.ws_connections.remove(ws)
            except Exception:
                pass

    def emit_sync(self, msg: str, kind: str = "info"):
        """Fire-and-forget emit from sync context (no broadcast)."""
        ts = datetime.now().strftime("%H:%M:%S")
        entry = json.dumps({"ts": ts, "msg": msg, "kind": kind})
        self.events.append(entry)


_sessions: Dict[str, Session] = {}

def get_or_create_session(session_id: str) -> Session:
    if session_id not in _sessions:
        _sessions[session_id] = Session(session_id)
    return _sessions[session_id]

