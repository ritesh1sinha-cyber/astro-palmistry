# Tesseract binary path — auto-detected; override via env TESSERACT_CMD
_TESSERACT_CMD: Optional[str] = os.getenv("TESSERACT_CMD") or None
_OCR_AVAILABLE: bool = False

def _init_ocr() -> bool:
    """Locate Tesseract and configure pytesseract. Returns True if ready."""
    global _TESSERACT_CMD, _OCR_AVAILABLE
    if _OCR_AVAILABLE:
        return True
    try:
        import pytesseract as _pt
        from PIL import Image as _PILImage  # noqa: F401 — verify Pillow is present
    except ImportError as exc:
        logger.warning(f"OCR disabled — missing library: {exc}. Install pytesseract and Pillow.")
        return False

    candidates: List[str] = []
    if _TESSERACT_CMD:
        candidates.append(_TESSERACT_CMD)
    candidates += [
        r"C:\Program Files\Tesseract-OCR\tesseract.exe",
        r"C:\Program Files (x86)\Tesseract-OCR\tesseract.exe",
        "/usr/bin/tesseract",
        "/usr/local/bin/tesseract",
    ]
    env_path = shutil.which("tesseract")
    if env_path:
        candidates.insert(0, env_path)

    for cmd in candidates:
        if cmd and os.path.isfile(cmd):
            _TESSERACT_CMD = cmd
            _pt.pytesseract.tesseract_cmd = cmd
            _OCR_AVAILABLE = True
            logger.info(f"Tesseract found: {cmd}")
            return True

    logger.warning("Tesseract executable not found — image OCR disabled.")
    return False


def _ocr_image_bytes(img_bytes: bytes) -> str:
    """Run Tesseract OCR on raw image bytes. Returns extracted text or ''."""
    if not _init_ocr():
        return ""
    try:
        import pytesseract as _pt
        from PIL import Image as _PILImage
        import io
        img = _PILImage.open(io.BytesIO(img_bytes)).convert("RGB")
        text = _pt.image_to_string(img, lang="chi_sim+eng", config="--psm 6")
        return text.strip()
    except Exception as exc:
        logger.debug(f"OCR failed for image: {exc}")
        return ""


def _ocr_image_file(path: str) -> str:
    """Run Tesseract OCR on an image file. Returns extracted text or ''."""
    if not _init_ocr():
        return ""
    try:
        import pytesseract as _pt
        from PIL import Image as _PILImage
        img = _PILImage.open(path).convert("RGB")
        text = _pt.image_to_string(img, lang="chi_sim+eng", config="--psm 6")
        return text.strip()
    except Exception as exc:
        logger.debug(f"OCR failed for file {path}: {exc}")
        return ""


def _export_slides_via_com(pptx_path: str, out_dir: str) -> List[str]:
    """Use PowerPoint COM automation (Windows) to export each slide as PNG.

    Returns a list of exported image file paths in slide order, or [] on failure.
    Only available on Windows with PowerPoint installed.
    """
    exported: List[str] = []
    try:
        import win32com.client as _win32
        import pythoncom
        pythoncom.CoInitialize()
        pptx_abs = os.path.abspath(pptx_path)
        out_abs = os.path.abspath(out_dir)
        os.makedirs(out_abs, exist_ok=True)
        ppt = _win32.Dispatch("PowerPoint.Application")
        ppt.Visible = 1
        try:
            prs_com = ppt.Presentations.Open(pptx_abs, ReadOnly=True, Untitled=False, WithWindow=False)
            try:
                for idx in range(1, prs_com.Slides.Count + 1):
                    img_path = os.path.join(out_abs, f"slide_{idx:03d}.png")
                    prs_com.Slides(idx).Export(img_path, "PNG", 1920, 1080)
                    if os.path.exists(img_path):
                        exported.append(img_path)
            finally:
                prs_com.Close()
        finally:
            ppt.Quit()
        pythoncom.CoUninitialize()
        logger.info(f"COM slide export: {len(exported)} slides → {out_abs}")
    except Exception as exc:
        logger.warning(f"PowerPoint COM export failed: {exc}")
    return exported


# ─────────────────────────── PPTX extraction ──────────────────────────
def _extract_pptx_text(file_path: str) -> str:
    """Extract all text (including OCR of embedded and rendered images) from a PPTX file.

    Strategy:
    1. Extract native text from text-frames and tables in all shapes/groups.
    2. For PICTURE shapes with an embedded blob → OCR the raw bytes directly.
    3. For PICTURE shapes with no embedded blob (OLE objects, charts, linked images)
       or slides that appear to have only visual content → fall back to rendering the
       entire slide via PowerPoint COM automation and OCR-ing the rendered PNG.
    """
    try:
        from pptx import Presentation as _Prs
        from pptx.enum.shapes import MSO_SHAPE_TYPE
    except ImportError:
        return f"[ERROR: python-pptx not installed. Cannot read {file_path}]"

    ocr_ready = _init_ocr()

    try:
        prs = _Prs(file_path)
        n_slides = len(prs.slides)

        # Track which slides need the COM slide-render fallback
        slides_needing_render: List[int] = []  # 1-based

        parts = [
            f"[Source file: {os.path.basename(file_path)}]",
            f"[Total slides: {n_slides}]",
            f"[OCR enabled: {ocr_ready}]",
            "",
        ]

        for i, slide in enumerate(prs.slides, 1):
            texts: List[str] = []
            ocr_texts: List[str] = []
            has_non_embedded_picture = False

            for shape in slide.shapes:
                try:
                    # ── text frames (includes GROUP which concatenates children) ──
                    try:
                        t = shape.text.strip()
                        if t:
                            texts.append(t)
                    except Exception:
                        pass

                    # ── tables ──
                    if shape.has_table:
                        for row in shape.table.rows:
                            for cell in row.cells:
                                if cell.text.strip():
                                    texts.append(cell.text.strip())

                    # ── PICTURE shapes ──
                    if ocr_ready and shape.shape_type == MSO_SHAPE_TYPE.PICTURE:
                        try:
                            img_bytes = shape.image.blob  # raises ValueError for OLE/linked
                            ocr_result = _ocr_image_bytes(img_bytes)
                            if ocr_result:
                                ocr_texts.append(
                                    f"[OCR from image '{shape.name}']: {ocr_result}"
                                )
                        except (ValueError, AttributeError):
                            # Non-embedded image (chart, OLE, linked) — mark for slide render
                            has_non_embedded_picture = True

                    # ── GROUP shapes — recurse one level for nested pictures ──
                    elif ocr_ready and shape.shape_type == MSO_SHAPE_TYPE.GROUP:
                        for child in shape.shapes:
                            try:
                                if child.shape_type == MSO_SHAPE_TYPE.PICTURE:
                                    try:
                                        img_bytes = child.image.blob
                                        ocr_result = _ocr_image_bytes(img_bytes)
                                        if ocr_result:
                                            ocr_texts.append(
                                                f"[OCR from grouped image '{child.name}']: {ocr_result}"
                                            )
                                    except (ValueError, AttributeError):
                                        has_non_embedded_picture = True
                            except Exception:
                                continue

                except Exception:
                    continue

            if has_non_embedded_picture:
                slides_needing_render.append(i)

            if texts or ocr_texts:
                parts.append(f"=== Slide {i} ===")
                parts.extend(texts)
                if ocr_texts:
                    parts.append("--- Image OCR text ---")
                    parts.extend(ocr_texts)
                parts.append("")
            elif not texts and not ocr_texts:
                parts.append(f"=== Slide {i} ===")
                parts.append("[No text content detected]")
                parts.append("")

        # ── COM fallback: render slides that had non-embedded images ──────────
        if ocr_ready and slides_needing_render:
            logger.info(
                f"Rendering {len(slides_needing_render)} slide(s) via PowerPoint COM for OCR: "
                + str(slides_needing_render)
            )
            tmp_dir = tempfile.mkdtemp(prefix="pptx_ocr_")
            try:
                exported = _export_slides_via_com(file_path, tmp_dir)
                if exported:
                    for slide_idx in slides_needing_render:
                        img_path = os.path.join(tmp_dir, f"slide_{slide_idx:03d}.png")
                        if os.path.exists(img_path):
                            ocr_result = _ocr_image_file(img_path)
                            if ocr_result:
                                # Insert OCR text after the existing slide section
                                marker = f"=== Slide {slide_idx} ==="
                                insert_at = -1
                                for pi, p in enumerate(parts):
                                    if p == marker:
                                        insert_at = pi
                                        break
                                if insert_at >= 0:
                                    # Find end of this slide section
                                    end_at = insert_at + 1
                                    while end_at < len(parts) and not parts[end_at].startswith("=== Slide "):
                                        end_at += 1
                                    parts.insert(end_at - 1, "--- Slide render OCR ---")
                                    parts.insert(end_at, ocr_result)
                                else:
                                    parts.append(f"=== Slide {slide_idx} (rendered OCR) ===")
                                    parts.append("--- Slide render OCR ---")
                                    parts.append(ocr_result)
                                    parts.append("")
            finally:
                shutil.rmtree(tmp_dir, ignore_errors=True)

        return "\n".join(parts)
    except Exception as e:
        return f"[ERROR extracting PPTX: {e}]"

# ────────────────────────── Cursor automation ─────────────────────────
class CursorAutomation:
    """Thin wrapper around cursor-agent CLI."""

    def __init__(self):
        self.cursor_agent_cmd = self._find_cmd()
        if self.cursor_agent_cmd:
            logger.info(f"cursor-agent found: {self.cursor_agent_cmd}")
        else:
            logger.warning("cursor-agent not found. Install Cursor CLI and add to PATH.")

    def _find_cmd(self) -> Optional[str]:
        for name in ("cursor-agent", "agent"):
            p = shutil.which(name)
            if p:
                return p
        if os.name != "nt":
            for p in (
                os.path.expanduser("~/.local/bin/cursor-agent"),
                os.path.expanduser("~/.local/bin/agent"),
                "/usr/local/bin/cursor-agent",
                "/usr/local/bin/agent",
            ):
                if os.path.exists(p) and os.access(p, os.X_OK):
                    return p
        return None

    def send_prompt(self, cwd: str, prompt: str, model: Optional[str] = None) -> Tuple[bool, Optional[str]]:
        if not self.cursor_agent_cmd:
            return False, None
        try:
            env = os.environ.copy()
            env["CURSOR_MODEL"] = model or "auto"

            use_stdin = os.name == "nt" and len(prompt) > 7500
            prompt_path: Optional[str] = None
            prompt_fh = None

            if use_stdin:
                fd, prompt_path = tempfile.mkstemp(suffix=".txt", prefix="bt_prompt_", text=True)
                try:
                    with os.fdopen(fd, "w", encoding="utf-8") as f:
                        f.write(prompt)
                    prompt_fh = open(prompt_path, "r", encoding="utf-8")
                    cmd = [self.cursor_agent_cmd, "-p", "--trust"]
                    if model:
                        cmd += ["--model", model]
                    cmd += ["--"]
                except Exception:
                    if prompt_fh:
                        try:
                            prompt_fh.close()
                        except Exception:
                            pass
                    if prompt_path and os.path.exists(prompt_path):
                        os.unlink(prompt_path)
                    use_stdin = False

            if not use_stdin:
                cmd = [self.cursor_agent_cmd, "-p", "--trust"]
                if model:
                    cmd += ["--model", model]
                cmd += ["--", prompt]

            proc = subprocess.Popen(
                cmd,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                stdin=prompt_fh if use_stdin else subprocess.DEVNULL,
                text=True,
                encoding="utf-8",
                env=env,
                cwd=cwd,
            )
            if use_stdin and prompt_fh:
                prompt_fh.close()

            lines: List[str] = []
            if proc.stdout:
                for line in proc.stdout:
                    lines.append(line)
            proc.wait()

            if proc.returncode == 0:
                return True, "".join(lines).strip()
            return False, None
        except Exception as e:
            logger.error(f"send_prompt error: {e}")
            return False, None
        finally:
            if prompt_path and os.path.exists(prompt_path):
                try:
                    os.unlink(prompt_path)
                except Exception:
                    pass

    def wait_for_files(self, workspace: str, files: List[str], max_minutes: int = 12) -> Optional[str]:
        req = [f.strip() for f in files if f.strip()]
        if not req:
            return None
        abs_paths = [os.path.join(workspace, n) for n in req]
        deadline = time.time() + max_minutes * 60
        found = {p: False for p in abs_paths}
        while time.time() < deadline:
            for p in abs_paths:
                if not found[p] and os.path.exists(p):
                    found[p] = True
            if all(found.values()):
                return abs_paths[0]
            time.sleep(5)
        return None

    def run(self, workspace: str, prompt: str, required_files: List[str], max_minutes: int = 12) -> Tuple[bool, Optional[str]]:
        if not os.path.exists(workspace):
            return False, None
        workspace = os.path.abspath(workspace)
        ok, _ = self.send_prompt(workspace, prompt)
        if not ok:
            return False, None
        out = self.wait_for_files(workspace, required_files, max_minutes)
        return (True, out) if out else (False, None)


