def _fetch_alm_details(alm_id: str) -> Optional[str]:
    """Fetch ALM bug details via Noah MCP and return as formatted text."""
    if not NOAH_MCP_API_KEY or not alm_id:
        return None
    url = NOAH_MCP_URL or "https://noah.oppo.local/mcp"
    try:
        resp = requests.post(
            url,
            headers={"Content-Type": "application/json", "x-mcp-apiKey": NOAH_MCP_API_KEY},
            json={"tool": "DMS-API0095", "parameters": {"id": alm_id, "collection": "OPPO"}},
            timeout=30,
        )
        if resp.status_code == 200:
            data = resp.json()
            result = data.get("result") or data.get("data") or data
            return json.dumps(result, ensure_ascii=False, indent=2)[:6000]
    except Exception as e:
        logger.warning(f"ALM fetch failed: {e}")
    return None

