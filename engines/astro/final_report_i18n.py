def MON(d: _dt.date, lang):
    if lang == "hi":
        return f"{MONTH_HI.get(d.month, d.month)} {d.year}"
    return d.strftime("%b %Y")


def ORDw(n, lang):
    if lang == "hi":
        return ORD_HI.get(n, str(n))
    return {1: "1st", 2: "2nd", 3: "3rd"}.get(n, f"{n}th")

