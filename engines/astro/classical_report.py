def _client_details(chart: BhardwajChart, *, name: str, dob: str, tob: str,
                    place: str, longevity_data: Optional[dict] = None) -> str:
    current_ad = next((a for a in chart.antars if a.get("status") == "current"), {})
    dasha = f"{chart.cur_md.get('md_lord', '')} Mahadasha"
    if current_ad.get("ad_lord"):
        dasha += f" with {current_ad['ad_lord']} Antardasha"
    rows = [
        ("Name", name or chart.name),
        ("Date of Birth", _pretty(dob) or dob),
        ("Time of Birth", tob),
        ("Place of Birth", place),
        ("Ascendant / Lagna", f"{chart.lagna} ({_lord_of(chart, 1)} lord)"),
        ("Moon Sign / Rashi", f"{chart.moon_sign}"),
        ("Nakshatra", chart.moon_nak),
        ("Current Dasha", dasha),
    ]
    if longevity_data:
        marakas = longevity_data.get("maraka_lords", [])
        if marakas:
            names = []
            for m in marakas:
                if isinstance(m, dict):
                    val = m.get("lord") or m.get("planet") or ""
                    if val and val not in names:
                        names.append(str(val))
                elif isinstance(m, str) and m and not m.startswith("{"):
                    if m not in names:
                        names.append(m)
            if names:
                rows.append(("Maraka Significators", ", ".join(names) + " (2nd & 7th lords)"))
        if longevity_data.get("tier"):
            rows.append(("Ayurdaya / Longevity", str(longevity_data["tier"])))

    body = "".join(
        f"<dt>{_e(k)}</dt><dd>{_e(v)}</dd>" for k, v in rows if str(v or "").strip()
    )
    return (
        '<section class="card"><h3 class="sec">Client Details</h3>'
        '<div style="background:#fff8e7;border-left:4px solid #b78103;padding:0.6rem 0.8rem;margin-bottom:1rem;font-size:0.88rem;color:#5a4100;">'
        '<b>Practitioner Consultation Brief:</b> This report compiles unfiltered classical readings across 9 traditional Jyotish systems '
        '(Bhardwaj, BNN Nadi, Mehta Modern, KP, Jaimini, Goel Medical, Ayurdaya, Ashtakavarga, and RTVD). All traditional indications, '
        'medical vulnerabilities, and planetary afflictions are retained without censorship for professional astrological consultation.'
        '</div>'
        f'<dl class="cv-detail">{body}</dl>'
        '<p class="sec-note">Every indication below is traced directly to classical Shastra principles, multi-engine cross-verification, and planetary dashas.</p>'
        "</section>"
    )


def _personality(chart: BhardwajChart, evidence: Optional[dict] = None) -> str:
    items: list[str] = []
    lagna_lord = _lord_of(chart, 1)

    plain = LAGNA_HUMAN.get(chart.lagna, "")
    if plain:
        items.append(CV.bullet(
            "Core temperament",
            f"{chart.lagna} rises in your chart, ruled by {lagna_lord}",
            plain,
        ))

    book = CV.book_clause((chart.book.get("lagna_signs") or {}).get(chart.lagna, ""),
                          direction="positive", domain="personality")
    if book:
        items.append(CV.bullet("Build and bearing",
                               f"the classical description of {chart.lagna} rising", book))

    if chart.moon_sign != chart.lagna:
        moon_house = _house_of(chart, "Moon")
        items.append(CV.bullet(
            "Emotional nature",
            f"your Moon sits in {chart.moon_sign} in the {_ord(moon_house)} house",
            f"inwardly you carry more {chart.moon_sign} than you show outwardly, "
            f"and your peace of mind is tied to {_HOUSE_TOPIC.get(moon_house, 'this area')}",
        ))

    star = NAKSHATRA_SNIPPETS.get(chart.moon_nak) or CV.book_clause(
        (chart.book.get("nakshatra_effects") or {}).get(chart.moon_nak, ""),
        domain="personality",
    )
    if star:
        items.append(CV.bullet("Birth star", f"your Moon is in {chart.moon_nak} nakshatra", star))

    lagna_book = _planet_book(chart, lagna_lord, domain="personality")
    lagna_house = _house_of(chart, lagna_lord)
    if lagna_house:
        items.append(CV.bullet(
            "How you apply yourself",
            CV.placement_cause(lagna_lord, lagna_house,
                               (chart.planets.get(lagna_lord) or {}).get("sign", ""),
                               (chart.planets.get(lagna_lord) or {}).get("dignity", "")),
            lagna_book or (
                f"as the ruler of your rising sign it carries your vitality into "
                f"{_HOUSE_TOPIC.get(lagna_house, 'that area of life')}"
            ),
        ))

    for planet in _tenants(chart, 1):
        if planet == lagna_lord:
            continue
        effect = _planet_book(chart, planet, domain="personality")
        if effect:
            items.append(CV.bullet(
                CV.label_for("personality", planet=planet),
                f"{planet} sits in your 1st house in {chart.planets[planet]['sign']}",
                effect,
            ))

    yogas = [y for y in chart.detect_yogas() if YOGA_HUMAN.get(y["name"])]
    yoga_labels = ("Standing combination", "A second combination")
    for index, yoga in enumerate(yogas[:2]):
        items.append(CV.bullet(yoga_labels[index], yoga["name"],
                               YOGA_HUMAN[yoga["name"]]))

    note = _consensus_note("personality", evidence or {})
    if note:
        items.append(note)

    close = (
        f"Taken together, {chart.lagna} rising with a {chart.moon_sign} Moon gives a person "
        "who is capable and self-directed. The work is to stay steady when the chart's "
        "weaker placements pull you off routine."
    )
    return _section("1. Personality Traits", items, close)


