def _remedy_planets(chart: BhardwajChart) -> list[tuple[str, str]]:
    """The planets this chart actually needs addressed, with the reason why."""
    md_lord = str(chart.cur_md.get("md_lord") or "")
    current_ad = next((a for a in chart.antars if a.get("status") == "current"), {})
    ad_lord = str(current_ad.get("ad_lord") or "")
    lagna_lord = _lord_of(chart, 1)

    picked: list[tuple[str, str]] = []
    seen: set[str] = set()

    def add(planet: str, reason: str) -> None:
        if planet in PLANETS and planet not in seen:
            picked.append((planet, reason))
            seen.add(planet)

    add(md_lord, "mahadasha lord — it governs the whole present chapter")
    add(ad_lord, "antardasha lord — it governs the months you are in")
    add(lagna_lord, "lord of your rising sign — it carries your vitality")
    for planet in PLANETS:
        info = chart.planets.get(planet) or {}
        if info.get("dignity") in WEAK_DIGNITY:
            add(planet, f"placed {str(info.get('dignity')).replace('_', ' ')}, so it needs support")
        elif int(info.get("house") or 0) in DUSTHANA:
            add(planet, f"placed in the {_ord(int(info['house']))} house, a difficult position")
    return picked[:6]


def _stone_reason(safety: dict, planet: str) -> str:
    """Why the stone is refused, in the report's own words rather than the engine's."""
    snap = safety.get("snap") or {}
    house = int(snap.get("house") or 0)
    dignity = str(snap.get("dignity") or "")
    if planet in ("Rahu", "Ketu"):
        return (f"the texts give {planet} a stone only on a clearly supportive placement, "
                "and this chart does not")
    if house in DUSTHANA:
        return f"{planet} sits in your {_ord(house)} house, which the texts read as a pressure house"
    if dignity in WEAK_DIGNITY:
        return f"{planet} is weak here, and its stone would magnify the weakness"
    return f"{planet} is already strong here, and its stone would overheat the result"


def _stone_line(gem: dict, safety: dict, planet: str) -> str:
    """Wear or do not wear, stated as a verdict. Never handed back to the client."""
    stone = gem.get("gem") or ""
    if not stone:
        return ""
    wear = safety.get("wear_mode") == "primary_ok"

    if wear:
        body = (
            f"{stone}, on the {gem.get('finger', 'ring finger')} in "
            f"{gem.get('metal', 'gold')}, started on a {gem.get('day', 'suitable day')}."
        )
        if safety.get("verdict") == "test_required":
            body += " Wear it on trial for three days first, then keep it on."
        return (
            f'<p class="cv-stone yes"><span class="cv-flag">Wear</span>'
            f"<b>Stone</b> — {_e(body)}</p>"
        )

    body = (
        f"{stone} is not advised for this chart, because {_stone_reason(safety, planet)}. "
        f"Use the {planet} mantra, charity and conduct above instead."
    )
    return (
        f'<p class="cv-stone no"><span class="cv-flag">Do not wear</span>'
        f"<b>Stone</b> — {_e(body)}</p>"
    )


def _remedies(chart: BhardwajChart, pc: dict) -> str:
    try:
        from gemstone_remedy import GEM_DATA, _gem_safety
    except Exception:  # noqa: BLE001
        return ""

    md_lord = str(chart.cur_md.get("md_lord") or "")
    ad_lord = str(
        next((a for a in chart.antars if a.get("status") == "current"), {}).get("ad_lord") or ""
    )
    lagna_lord = _lord_of(chart, 1)

    try:
        import json
        from pathlib import Path
        goel = json.loads(
            (Path(__file__).resolve().parent / "goel_disease_book_data.json")
            .read_text(encoding="utf-8")
        ).get("planet_remedy") or {}
    except Exception:  # noqa: BLE001
        goel = {}

    cards: list[str] = []
    for planet, reason in _remedy_planets(chart):
        gem = GEM_DATA.get(planet) or {}
        mantra = gem.get("mantra") or (goel.get(planet) or {}).get("mantra") or ""
        charity = gem.get("charity") or (goel.get(planet) or {}).get("charity") or ""
        behavior = gem.get("behavior") or ""

        lines = []
        if mantra:
            lines.append(f"<p><b>Mantra</b> — {_e(mantra)}</p>")
        if charity:
            lines.append(f"<p><b>Charity</b> — {_e(charity)} </p>")
        if behavior:
            lines.append(f"<p><b>Conduct</b> — {_e(behavior)}</p>")
        # Every planet gets a decision. The client is never asked to have the
        # stone "checked" — that check is this report's job.
        try:
            safety = _gem_safety(
                pc, planet,
                role="Lagna lord" if planet == lagna_lord else "",
                is_md=planet == md_lord,
                is_ad=planet == ad_lord,
            )
        except Exception as exc:  # noqa: BLE001
            print(f"[classical_report] gem safety unavailable: {exc}", flush=True)
            safety = {"wear_mode": "", "verdict": "avoid", "reasons": []}
        stone_line = _stone_line(gem, safety, planet)
        if stone_line:
            lines.append(stone_line)
        cards.append(
            f'<div class="cv-remedy"><h4>For {_e(planet)}</h4>'
            f'<p class="cv-why">Why this planet: {_e(reason)}.</p>'
            + "".join(lines) + "</div>"
        )

    if not cards:
        return ""
    close = (
        "Remedies in the classical system are corrective, not magical. Conduct comes first, "
        "then mantra and charity, and only then a stone."
    )
    return (
        '<section class="card"><h3 class="sec">10. Remedies and Guidance</h3>'
        '<p class="sec-note">Chosen for the planets that actually rule your chart and your '
        'present period, not a general list.</p>'
        + "".join(cards)
        + f'<p class="cv-close">{_e(close)}</p></section>'
    )


def _summary(chart: BhardwajChart, buckets: list[dict]) -> str:
    md_lord = str(chart.cur_md.get("md_lord") or "")
    current_ad = next((a for a in chart.antars if a.get("status") == "current"), {})
    ad_lord = str(current_ad.get("ad_lord") or "")
    near = buckets[0] if buckets else {}
    near_names = CT.ruling_lords(near)[:2] if near else []
    near_lords = _join(near_names)

    # The opening line must describe this lagna, not a generic one.
    signature = (LAGNA_HUMAN.get(chart.lagna) or "").split(".")[0].strip()
    opening = (
        f"You were born with {chart.lagna} rising and the Moon in {chart.moon_sign} "
        f"({chart.moon_nak})."
    )
    if signature:
        opening += f" {signature}."

    parts = [
        opening,
        f"Your life is presently running through the {md_lord} mahadasha"
        + (f" with {ad_lord} antardasha" if ad_lord else "")
        + f" — a chapter that {_LORD_EFFECT.get(md_lord, 'sets the tone of these years')}.",
    ]
    if near_lords:
        single = len(dict.fromkeys(near_names)) == 1
        parts.append(
            f"Over the coming months {near_lords} "
            + ("rules" if single else "rule")
            + " the timing, so the areas "
            + ("that planet owns" if single else "those planets own")
            + " are where effort pays."
        )
    parts.append(
        "The classical advice for this chart is the same as the classical advice for the "
        "period: keep the routine, respect the people the chart marks as helpful, and use "
        "the remedies for the planets named above."
    )
    body = " ".join(parts)
    return (
        '<section class="card"><h3 class="sec">Summary</h3>'
        f"<p>{_e(body)}</p></section>"
    )


