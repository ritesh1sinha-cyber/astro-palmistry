def _e(value: Any) -> str:
    return html.escape(str(value or ""))


def _ord(n: int) -> str:
    n = int(n)
    if 10 <= n % 100 <= 20:
        return f"{n}th"
    return f"{n}" + {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")


def _pretty(value) -> str:
    if isinstance(value, datetime):
        value = value.date()
    if not isinstance(value, date):
        try:
            value = datetime.strptime(str(value or "")[:10], "%Y-%m-%d").date()
        except ValueError:
            return str(value or "")[:10]
    return value.strftime("%d %b %Y").lstrip("0")


def _rules_phrase(chart: BhardwajChart, planet: str) -> str:
    """How a planet holds power. Rahu and Ketu own no sign, so they act by house."""
    ruled = chart.rules.get(planet) or []
    if ruled:
        return "rules your " + " and ".join(_ord(h) for h in ruled) + " house"
    house = _house_of(chart, planet)
    if house:
        return (f"owns no sign of its own and acts from the {_ord(house)} house "
                "it occupies")
    return "acts through the houses it touches"


def _focus_house(chart: BhardwajChart, planet: str) -> int:
    """The house a planet actually moves. Ownership first, occupancy for nodes."""
    ruled = chart.rules.get(planet) or []
    if ruled:
        return ruled[0]
    return _house_of(chart, planet) or 1


def _join(names: list[str]) -> str:
    names = list(dict.fromkeys(n for n in names if n))
    if len(names) <= 1:
        return names[0] if names else ""
    return ", ".join(names[:-1]) + " and " + names[-1]


def _house_of(chart: BhardwajChart, planet: str) -> int:
    return int((chart.planets.get(planet) or {}).get("house") or 0)


def _lord_of(chart: BhardwajChart, house: int) -> str:
    return str((chart.houses.get(house) or {}).get("lord") or "")


def _tenants(chart: BhardwajChart, house: int) -> list[str]:
    return [p for p in PLANETS if _house_of(chart, p) == house]


def _planet_book(chart: BhardwajChart, planet: str, *, domain: str) -> str:
    info = chart.planets.get(planet) or {}
    house = int(info.get("house") or 0)
    if not house:
        return ""
    raw = (chart.book.get("planet_in_house") or {}).get(str(house), {}).get(planet, "")
    direction = "caution" if info.get("dignity") in WEAK_DIGNITY else "positive"
    return CV.book_clause(raw, dignity=str(info.get("dignity") or ""),
                          direction=direction, domain=domain)


def _lord_book(chart: BhardwajChart, lord_of: int, *, domain: str) -> tuple[int, str]:
    lord = _lord_of(chart, lord_of)
    lord_in = _house_of(chart, lord)
    if not lord or not lord_in:
        return 0, ""
    raw = (chart.book.get("house_lord_in_house") or {}).get(str(lord_of), {}).get(str(lord_in), "")
    direction = "caution" if lord_in in DUSTHANA else "neutral"
    return lord_in, CV.book_clause(raw, direction=direction, domain=domain)


def _lord_bullet(chart: BhardwajChart, house: int, label: str, *, domain: str) -> str:
    """The house lord's placement, stated the way an astrologer states it."""
    lord = _lord_of(chart, house)
    lord_in, book = _lord_book(chart, house, domain=domain)
    if not lord_in:
        return ""
    cause = CV.lord_cause(lord, house, lord_in)
    if lord_in == house:
        # A lord in its own house has nowhere else to point the reader.
        default = (
            f"matters of {_HOUSE_TOPIC.get(house, 'this area')} are held in the lord's own "
            "house, so this part of life runs on its own terms rather than depending on "
            "another"
        )
    else:
        default = (
            f"matters of {_HOUSE_TOPIC.get(house, 'this area')} are therefore reached through "
            f"{_HOUSE_TOPIC.get(lord_in, 'that part of life')}"
        )
    effect = book or default
    return CV.bullet(label, cause, effect)


