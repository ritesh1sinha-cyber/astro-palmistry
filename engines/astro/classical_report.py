_LAGNA_VERB = re.compile(
    r"^\w+\s+(?:rising\s+)?"
    r"(?P<verb>gives|makes|adds|brings|opens|steadies|softens|colours)\s+(?P<rest>.+)$",
    re.I,
)


def _child_trait(sign: str) -> str:
    """The lagna description, re-pointed at a child rather than at the reader."""
    match = _LAGNA_VERB.match((LAGNA_HUMAN.get(sign) or "").split(".")[0].strip())
    if not match:
        return ""
    rest = match.group("rest").strip()
    if match.group("verb").lower() == "makes" and rest.lower().startswith("you "):
        return f"the sign makes the child {rest[4:]}"
    # "steadies the personality with patience ..." — drop the carrier phrase.
    rest = re.sub(r"^the [a-z ]+? (?:with|towards?) ", "", rest, flags=re.I)
    return f"the sign gives the child {rest}"


